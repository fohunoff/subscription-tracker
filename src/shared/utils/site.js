/**
 * Ссылка на сервис подписки и иконка по ней.
 *
 * Своего пака логотипов в трекере нет и не планируется: любой готовый набор
 * покрывает только известные бренды, а в списке рядом с Netflix живут
 * мобильный оператор и коммуналка. Поэтому иконка берётся из favicon сайта —
 * он есть у всего, у чего вообще есть сайт.
 *
 * Источник — сервис Google (s2/favicons): он сам ходит на сайт, кэширует и
 * отдаёт нужный размер. Цена решения — домен сервиса уходит запросом к Google;
 * если это станет неприемлемо, менять нужно ровно getFaviconUrl — например,
 * на собственный прокси с кэшем.
 */

/** Хост без www — короткая подпись ссылки и ключ для favicon. */
export const getSiteHost = (url) => {
  if (!url) return null;
  try {
    return new URL(url).hostname.replace(/^www\./, '');
  } catch {
    // В базе лежат только нормализованные ссылки, но старые записи и импорт
    // могут принести что угодно — на битой строке иконка просто не покажется
    return null;
  }
};

/**
 * Ширина картинки-заглушки, которую сервис отдаёт вместо неизвестной иконки.
 *
 * Отличить «иконки нет» по коду ответа нельзя: заглушка приходит с 404, но
 * телом валидного PNG — браузер рисует её как обычную картинку, и onError на
 * <img> не срабатывает. Зато она всегда 16×16 (серый глобус), тогда как
 * настоящие иконки приходят в запрошенном размере. Это и есть признак —
 * см. ServiceIcon, который по нему переключается на букву названия.
 */
export const FAVICON_PLACEHOLDER_WIDTH = 16;

/**
 * URL картинки favicon для ссылки на сервис. null — если ссылки нет.
 *
 * Размер по умолчанию один на все места показа намеренно: карточка в списке и
 * панель деталей просят одну и ту же картинку, и вторая берётся из кэша.
 */
export const getFaviconUrl = (url, size = 128) => {
  const host = getSiteHost(url);
  if (!host) return null;
  return `https://www.google.com/s2/favicons?domain=${encodeURIComponent(host)}&sz=${size}`;
};
